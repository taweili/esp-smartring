/* ------------------------------------------------------------- state */

typedef enum {
    WS_MSG_TEXT = 0,   /* assembled JSON text message */
    WS_MSG_LIFECYCLE, /* connection lifecycle (CONNECTED/DISCONNECTED/ERROR) */
    WS_MSG_STOP,
} ws_msg_kind_t;

typedef struct {
    ws_msg_kind_t kind;
    int   len;       /* valid bytes in data (text) */
    int   err_type;  /* lifecycle: WEBSOCKET_ERROR_TYPE_* or 0 */
} ws_msg_t;

typedef struct {
    ring_ws_state_t         state;
    ring_ws_state_cb_t      state_cb;
    ring_ws_transcript_cb_t text_cb;
    ring_ws_tool_cb_t       tool_cb;
    void                   *user;

    esp_websocket_client_handle_t client;

    TaskHandle_t             worker_task;
    TaskHandle_t             event_task;

    char                     model[64];
    char                     api_key[160];
    ring_ws_session_cfg_t    cfg;     /* copied at start */

    char                     turn_mode[24];  /* negotiated mode for UI */

    /* Reassembly: one buffer per active message, owned by the WS task. */
    uint8_t                 *reasm;
    int                      reasm_len;
    int                      reasm_cap;
    SemaphoreHandle_t        reasm_ack;   /* worker finished with s.reasm */

    /* Inbound delta scratch (PSRAM): base64 text + decoded 24 kHz PCM. */
    char                    *b64_text;
    size_t                   b64_cap;
    uint8_t                 *pcm24_scratch;
    size_t                   pcm24_cap;

    /* Uplink scratch (internal RAM). One writer task only (see header). */
    int16_t                  up16[RING_WS_UP16_SAMPLES];
    char                     up_b64[RING_WS_UP_B64_MAX];
    char                     up_json[RING_WS_UP_JSON_MAX];

    /* Worker <-> WS-task queue: pushes ws_msg_t when a message completes. */
    QueueHandle_t            msg_queue;
    /* Lifecycle queue entry scratch (avoid stack alloc on WS task). */
    ws_msg_t                 lifecycle_msg;

    /* Downlink PCM ring buffer (24 kHz mono, 192 KB). */
    ring_byte_ring_t         dl_ring;

    /* Resampler state. */
    ring_resample_decim_t    decim;
    ring_resample_interp_t   interp;
    float                    decim_out[RING_WS_FRAME_SAMPLES / 3 + 8]; /* 320 */
    float                    interp_out[RING_WS_FRAME_SAMPLES * 2 + 32]; /* 1920 */

    /* Half-duplex / turn tracking. */
    volatile bool            responding;     /* set on response.created, cleared on response.done */
    volatile bool            speaking;       /* mirror of responding for the app */
    uint32_t                 last_playback_ms;  /* last ring_audio_write time */
    uint32_t                 response_start_ms; /* watchdog */
    uint32_t                 cushion_ms;       /* current cushion target */

    /* Stats. */
    uint32_t                 bytes_up;
    uint32_t                 bytes_down;
    uint32_t                 turns;
    uint32_t                 dropped_up;
    uint32_t                 dropped_down;
    uint32_t                 ring_high_samples;  /* at 24 kHz */
    uint32_t                 buffered_high_ms;

    /* Event marshalling: a single-slot queue of state values. */
    QueueHandle_t            event_queue;
    SemaphoreHandle_t        state_mutex;
} ring_ws_ctx_t;

static ring_ws_ctx_t s;

/* ------------------------------------------------------------- helpers */

const char *ring_ws_state_name(ring_ws_state_t st)
{
    switch (st) {
    case RING_WS_OFF:        return "off";
    case RING_WS_CONNECTING: return "connecting";
    case RING_WS_READY:      return "ready";
    case RING_WS_LISTENING:  return "listening";
    case RING_WS_SPEAKING:   return "speaking";
    case RING_WS_ERROR:      return "error";
    }
    return "?";
}

static uint32_t now_ms(void)
{
    return (uint32_t)(esp_timer_get_time() / 1000);
}

/* State change with event-task notification (same pattern as ring_net). */
static void state_set(ring_ws_state_t st)
{
    if (s.state_mutex != NULL) {
        xSemaphoreTake(s.state_mutex, portMAX_DELAY);
    }
    if (s.state == st) {
        if (s.state_mutex != NULL) {
            xSemaphoreGive(s.state_mutex);
        }
        return;
    }
    s.state = st;
    if (s.state_mutex != NULL) {
        xSemaphoreGive(s.state_mutex);
    }
    ESP_LOGI(TAG, "state -> %s", ring_ws_state_name(st));
    if (s.event_queue) {
        xQueueOverwrite(s.event_queue, &st);
        if (s.event_task) {
            xTaskNotifyGive(s.event_task);
        }
    }
}

/* A lost response.done would keep the half-duplex gate closed forever. */
static void response_watchdog(void)
{
    if (s.responding &&
        (now_ms() - s.response_start_ms) > RING_WS_RESPONSE_WATCHDOG_MS) {
        ESP_LOGW(TAG, "no response.done after %u ms - cancelling",
                 (unsigned)(now_ms() - s.response_start_ms));
        s.responding = false;
        s.speaking = false;
        if (ring_ws_state() == RING_WS_SPEAKING) {
            state_set(RING_WS_READY);
        }
    }
}

/* ------------------------------------------------------------- downlink ring (24 kHz) */

static void dl_push(const uint8_t *pcm, size_t len)
{
    size_t dropped = 0;
    ring_byte_ring_push(&s.dl_ring, pcm, len, &dropped);
    s.dropped_down += (uint32_t)dropped;

    size_t cur = ring_byte_ring_count(&s.dl_ring) / 2;   /* samples (24 kHz) */
    if (cur > s.ring_high_samples) {
        s.ring_high_samples = (uint32_t)cur;
    }
}

static size_t dl_pop(uint8_t *pcm, size_t len)
{
    return ring_byte_ring_pop(&s.dl_ring, pcm, len);
}

static size_t dl_count_bytes(void)
{
    return ring_byte_ring_count(&s.dl_ring);
}

uint32_t ring_ws_buffered_ms(void)
{
    /* 24 kHz mono, 2 bytes/sample -> ms = bytes / (2 * 24) */
    return (uint32_t)(dl_count_bytes() / (2 * (RING_WS_OUT_RATE / 1000)));
}

bool ring_ws_playback_pending(void)
{
    if (ring_ws_is_speaking()) {
        return true;
    }
    return ring_ws_buffered_ms() > 0;
}

/* ------------------------------------------------------------- base64 send/recv */

/* base64-encode `in` (n bytes) into a NUL-terminated string in `out`.
 * Returns ESP_OK or an mbedtls error. `out` must hold 4/3 * n + 1 bytes. */
static esp_err_t b64_encode(const uint8_t *in, size_t n, char *out, size_t out_cap, size_t *out_len)
{
    size_t olen = 0;
    int ret = mbedtls_base64_encode((unsigned char *)out, out_cap, &olen, in, n);
    if (ret != 0) {
        return ESP_FAIL;
    }
    out[olen] = '\0';
    if (out_len) {
        *out_len = olen;
    }
    return ESP_OK;
}

/* base64-decode `in` (NUL-terminated) into `out`. Returns bytes written. */
static int b64_decode(const char *in, size_t in_len, uint8_t *out, size_t out_cap)
{
    size_t olen = 0;
    int ret = mbedtls_base64_decode(out, out_cap, &olen,
                                    (const unsigned char *)in, in_len);
    if (ret != 0) {
        return -1;
    }
    return (int)olen;
}

/* ------------------------------------------------------------- protocol send */

esp_err_t ring_ws_send_json(const char *json)
{
    if (s.client == NULL || json == NULL) {
        return ESP_ERR_INVALID_STATE;
    }
    int len = (int)strlen(json);
    int w = esp_websocket_client_send_text(s.client, json, len,
                                           pdMS_TO_TICKS(RING_WS_SEND_TIMEOUT_MS));
    if (w < 0) {
        return ESP_FAIL;
    }
    s.bytes_up += (uint32_t)w;
    return ESP_OK;
}

/* Append formatted text to a fixed JSON buffer; returns false on overflow.
 * `snprintf` reports the would-be length, so a plain `n += snprintf(...)`
 * would underflow `sizeof(json) - n` on the next call and write out of
 * bounds. */
static bool json_append(char *buf, size_t cap, int *pos, const char *fmt, ...)
{
    if (*pos < 0 || (size_t)*pos >= cap) {
        return false;
    }
    va_list ap;
    va_start(ap, fmt);
    int w = vsnprintf(buf + *pos, cap - (size_t)*pos, fmt, ap);
    va_end(ap);
    if (w < 0 || (size_t)w >= cap - (size_t)*pos) {
        *pos = (int)cap;
        return false;
    }
    *pos += w;
    return true;
}

/* Build and send a session.update event from the stored cfg.
 * If `turn_detection` is non-NULL it overrides cfg.turn_detection. */
static esp_err_t send_session_update(const char *turn_detection_override)
{
    char json[1024];
    int n = 0;
    const ring_ws_session_cfg_t *c = &s.cfg;
    const char *td = turn_detection_override ? turn_detection_override : c->turn_detection;

    if (!json_append(json, sizeof(json), &n,
                     "{\"type\":\"session.update\",\"session\":{"
                     "\"modalities\":[\"text\",\"audio\"]")) {
        goto overflow;
    }
    if (c->voice &&
        !json_append(json, sizeof(json), &n, ",\"voice\":\"%s\"", c->voice)) {
        goto overflow;
    }
    if (c->instructions) {
        if (!json_append(json, sizeof(json), &n, ",\"instructions\":")) {
            goto overflow;
        }
        if (!ring_json_append_string(json, sizeof(json), &n, c->instructions)) {
            goto overflow;
        }
    }
    if (c->speech_rate > 0.0f &&
        !json_append(json, sizeof(json), &n, ",\"speech_rate\":%.2f", c->speech_rate)) {
        goto overflow;
    }
    if (c->max_history_turns > 0 &&
        !json_append(json, sizeof(json), &n, ",\"max_history_turns\":%d",
                     c->max_history_turns)) {
        goto overflow;
    }
    if (c->enable_search &&
        !json_append(json, sizeof(json), &n, ",\"enable_search\":true")) {
        goto overflow;
    }
    if (c->input_language &&
        !json_append(json, sizeof(json), &n,
                     ",\"input_audio_transcription\":{\"language\":\"%s\"}",
                     c->input_language)) {
        goto overflow;
    }
    if (c->output_language &&
        !json_append(json, sizeof(json), &n,
                     ",\"output_audio\":{\"language\":\"%s\"}",
                     c->output_language)) {
        goto overflow;
    }
    if (td == NULL) {
        if (!json_append(json, sizeof(json), &n, ",\"turn_detection\":null")) {
            goto overflow;
        }
    } else if (strcmp(td, "server_vad") == 0) {
        if (!json_append(json, sizeof(json), &n,
                         ",\"turn_detection\":{\"type\":\"server_vad\","
                         "\"threshold\":0.5,\"silence_duration_ms\":800}")) {
            goto overflow;
        }
    } else {
        /* smart_turn / smart_turn_v2: silence_duration_ms is ignored. */
        if (!json_append(json, sizeof(json), &n,
                         ",\"turn_detection\":{\"type\":\"%s\",\"threshold\":0.5}",
                         td)) {
            goto overflow;
        }
    }
    if (c->tools_json &&
        !json_append(json, sizeof(json), &n, ",\"tools\":%s", c->tools_json)) {
        goto overflow;
    }
    if (!json_append(json, sizeof(json), &n, "}}")) {
        goto overflow;
    }

    ESP_LOGI(TAG, "session.update: turn_detection=%s",
             td ? td : "null");
    return ring_ws_send_json(json);

overflow:
    ESP_LOGE(TAG, "session.update too long");
    return ESP_FAIL;
}

/* ------------------------------------------------------------- protocol receive (worker) */

/* Decode a response.audio.delta's base64 PCM (24 kHz mono) and push to ring. */
static void handle_audio_delta(const char *json)
{
    /* Find the "delta" string value. The scratch buffer is PSRAM and as big
     * as the reassembly buffer, so a completed message always fits. */
    size_t blen = 0;
    if (!ring_json_get_str(json, "delta", s.b64_text, s.b64_cap, &blen)) {
        return;
    }
    if (blen == 0) {
        return;
    }
    if (blen + 1 >= s.b64_cap) {
        ESP_LOGW(TAG, "audio delta too big (%u B) - dropped", (unsigned)blen);
        return;
    }

    int n = b64_decode(s.b64_text, blen, s.pcm24_scratch, s.pcm24_cap);
    if (n <= 0) {
        ESP_LOGW(TAG, "audio delta: base64 decode failed (%u B)",
                 (unsigned)blen);
        s.dropped_down += (uint32_t)blen;
        return;
    }
    s.bytes_down += (uint32_t)n;
    dl_push(s.pcm24_scratch, (size_t)n);
}

/* Process a complete JSON message from the worker queue. */
static void worker_handle_text(const char *json, int len)
{
    /* DEBUG only: an audio delta is a ~6 KB JSON message and there are dozens
     * per reply. Logging them at INFO floods the USB-Serial-JTAG console,
     * which blocks the WS worker whenever no monitor is attached. */
    ESP_LOGD(TAG, "ws: %.*s", len > 200 ? 200 : len, json);

    if (ring_json_type_is(json, "session.created")) {
        ESP_LOGI(TAG, "session created -> configuring");
        send_session_update(NULL);
        return;
    }
    if (ring_json_type_is(json, "session.updated")) {
        ESP_LOGI(TAG, "session configured");
        state_set(RING_WS_READY);
        return;
    }
    if (ring_json_type_is(json, "response.created")) {
        s.responding = true;
        s.speaking = true;
        s.response_start_ms = now_ms();
        ring_ws_state_t st = ring_ws_state();
        if (st == RING_WS_READY || st == RING_WS_LISTENING) {
            state_set(RING_WS_SPEAKING);
        }
        return;
    }
    if (ring_json_type_is(json, "response.done")) {
        s.responding = false;
        s.speaking = false;
        s.turns++;
        if (ring_ws_state() == RING_WS_SPEAKING) {
            state_set(RING_WS_READY);
        }
        return;
    }
    if (ring_json_type_is(json, "input_audio_buffer.speech_started")) {
        /* In hands-free modes this means the server heard speech while the
         * uplink was open — barge-in. Cancel the current response and flush
         * the downlink. (In PTT mode this event doesn't fire.) */
        if (s.responding) {
            ESP_LOGI(TAG, "barge-in: speech_started");
            ring_ws_cancel();
        }
        return;
    }
    if (ring_json_type_is(json, "input_audio_buffer.speech_stopped") ||
        ring_json_type_is(json, "input_audio_buffer.committed")) {
        return;
    }
    if (ring_json_type_is(json, "response.audio.delta")) {
        handle_audio_delta(json);
        return;
    }
    if (ring_json_type_is(json, "response.audio_transcript.delta") ||
        ring_json_type_is(json, "response.text.delta")) {
        if (s.text_cb) {
            char text[256];
            size_t tlen = 0;
            if (ring_json_get_str(json, "delta", text, sizeof(text), &tlen)) {
                s.text_cb(text, tlen, false, s.user);
            }
        }
        return;
    }
    if (ring_json_type_is(json, "response.audio_transcript.done")) {
        char text[256];
        size_t tlen = 0;
        /* The Qianwen/OpenAI shape calls the finished string "transcript";
         * "text" is accepted as a fallback. */
        if (ring_json_get_str(json, "transcript", text, sizeof(text), &tlen) ||
            ring_json_get_str(json, "text", text, sizeof(text), &tlen)) {
            ESP_LOGI(TAG, "reply: %s", text);
            if (s.text_cb) {
                s.text_cb(text, tlen, false, s.user);
            }
        }
        return;
    }
    if (ring_json_type_is(json, "conversation.item.input_audio_transcription.completed")) {
        char text[256];
        size_t tlen = 0;
        if (ring_json_get_str(json, "transcript", text, sizeof(text), &tlen)) {
            ESP_LOGI(TAG, "heard: %s", text);
            if (s.text_cb) {
                s.text_cb(text, tlen, true, s.user);
            }
        }
        return;
    }
    if (ring_json_type_is(json, "response.function_call_arguments.done")) {
        if (s.tool_cb) {
            char name[64] = {0};
            char args[512] = {0};
            size_t nl = 0, al = 0;
            ring_json_get_str(json, "name", name, sizeof(name), &nl);
            ring_json_get_str(json, "arguments", args, sizeof(args), &al);
            if (nl > 0) {
                s.tool_cb(name, args, s.user);
            }
        }
        return;
    }
    if (ring_json_type_is(json, "error")) {
        char etype[64] = {0};
        char eparam[128] = {0};
        size_t el = 0;
        ring_json_get_str(json, "type", etype, sizeof(etype), &el);  /* error.type is nested */
        /* The nested error block: re-search from after "error" */
        const char *ep = strstr(json, "\"error\"");
        if (ep) {
            ring_json_get_str(ep, "type", etype, sizeof(etype), &el);
            ring_json_get_str(ep, "param", eparam, sizeof(eparam), &el);
        }
        ESP_LOGW(TAG, "error: type=%s param=%s", etype, eparam);
        /* smart_turn_v2 -> server_vad fallback on a turn_detection error,
         * only before any audio was sent (still IDLE/CONNECTING/READY). */
        ring_ws_state_t st = ring_ws_state();
        if (strstr(eparam, "turn_detection") &&
            st != RING_WS_LISTENING && st != RING_WS_SPEAKING &&
            s.cfg.turn_detection != NULL &&
            strcmp(s.cfg.turn_detection, "server_vad") != 0) {
            ESP_LOGI(TAG, "falling back to server_vad");
            snprintf(s.turn_mode, sizeof(s.turn_mode), "server_vad");
            send_session_update("server_vad");
        } else if (strcmp(etype, "server_error") == 0) {
            state_set(RING_WS_ERROR);
        }
        return;
    }
}

static void worker_handle_lifecycle(ws_msg_t *m)
{
    switch (m->err_type) {
    case 0:  /* CONNECTED */
        ESP_LOGI(TAG, "ws connected");
        break;
    case WEBSOCKET_ERROR_TYPE_HANDSHAKE:
        ESP_LOGE(TAG, "ws handshake failed (auth?)");
        state_set(RING_WS_ERROR);
        break;
    case WEBSOCKET_ERROR_TYPE_TCP_TRANSPORT:
    case WEBSOCKET_ERROR_TYPE_PONG_TIMEOUT:
    case WEBSOCKET_ERROR_TYPE_SERVER_CLOSE:
        ESP_LOGW(TAG, "ws disconnected (err=%d)", m->err_type);
        if (ring_ws_state() != RING_WS_OFF) {
            state_set(RING_WS_ERROR);
        }
        break;
    default:
        break;
    }
}

/* ------------------------------------------------------------- worker task */

static void worker_task(void *arg)
{
    (void)arg;
    ws_msg_t msg;
    for (;;) {
        if (xQueueReceive(s.msg_queue, &msg, portMAX_DELAY) != pdTRUE) {
            continue;
        }
        if (msg.kind == WS_MSG_STOP) {
            break;
        }
        if (msg.kind == WS_MSG_TEXT) {
            /* The data is in s.reasm (shared buffer with WS task). The WS
             * task is blocked in reasm_ack until we give it back. */
            worker_handle_text((const char *)s.reasm, msg.len);
            xSemaphoreGive(s.reasm_ack);
        } else if (msg.kind == WS_MSG_LIFECYCLE) {
            worker_handle_lifecycle(&msg);
        }
    }
    vTaskDelete(NULL);
}

/* ------------------------------------------------------------- event task */

static void event_task(void *arg)
{
    (void)arg;
    for (;;) {
        ulTaskNotifyTake(pdTRUE, portMAX_DELAY);
        ring_ws_state_t st;
        if (xQueuePeek(s.event_queue, &st, 0) == pdTRUE && s.state_cb) {
            s.state_cb(st, s.user);
        }
    }
}

/* ------------------------------------------------------------- WS event handler
 *
 * Runs on the esp_websocket_client task. Must stay minimal: copy fragments,
 * push completed messages, post lifecycle events. No JSON, no base64, no LVGL.
 */
static void ws_event_handler(void *arg, esp_event_base_t base,
                             int32_t event_id, void *event_data)
{
    (void)arg;
    (void)base;
    esp_websocket_event_data_t *data = (esp_websocket_event_data_t *)event_data;

    switch (event_id) {
    case WEBSOCKET_EVENT_CONNECTED:
        ESP_LOGI(TAG, "WEBSOCKET_EVENT_CONNECTED");
        s.lifecycle_msg.kind = WS_MSG_LIFECYCLE;
        s.lifecycle_msg.err_type = 0;
        xQueueSend(s.msg_queue, &s.lifecycle_msg, portMAX_DELAY);
        break;

    case WEBSOCKET_EVENT_DISCONNECTED:
        ESP_LOGI(TAG, "WEBSOCKET_EVENT_DISCONNECTED");
        s.lifecycle_msg.kind = WS_MSG_LIFECYCLE;
        s.lifecycle_msg.err_type = WEBSOCKET_ERROR_TYPE_TCP_TRANSPORT;
        xQueueSend(s.msg_queue, &s.lifecycle_msg, portMAX_DELAY);
        break;

    case WEBSOCKET_EVENT_ERROR:
        ESP_LOGW(TAG, "WEBSOCKET_EVENT_ERROR type=%d",
                 data ? data->error_handle.error_type : -1);
        s.lifecycle_msg.kind = WS_MSG_LIFECYCLE;
        s.lifecycle_msg.err_type = data ? data->error_handle.error_type
                                       : WEBSOCKET_ERROR_TYPE_TCP_TRANSPORT;
        xQueueSend(s.msg_queue, &s.lifecycle_msg, portMAX_DELAY);
        break;

    case WEBSOCKET_EVENT_CLOSED:
        ESP_LOGI(TAG, "WEBSOCKET_EVENT_CLOSED");
        s.lifecycle_msg.kind = WS_MSG_LIFECYCLE;
        s.lifecycle_msg.err_type = WEBSOCKET_ERROR_TYPE_SERVER_CLOSE;
        xQueueSend(s.msg_queue, &s.lifecycle_msg, portMAX_DELAY);
        break;

    case WEBSOCKET_EVENT_DATA: {
        if (data == NULL || data->data_len <= 0) {
            break;
        }
        /* Only reassemble text frames (op_code 1). Pong/close are op 0xA/0x8. */
        if (data->op_code != 1) {
            break;
        }
        /* Accumulate into the reassembly buffer at the current offset. */
        int offset = data->payload_offset;
        if (offset + data->data_len > s.reasm_cap) {
            ESP_LOGW(TAG, "fragment too big: %d+%d > %d",
                     offset, data->data_len, s.reasm_cap);
            break;
        }
        memcpy(s.reasm + offset, data->data_ptr, data->data_len);
        if (data->fin && (offset + data->data_len) >= data->payload_len) {
            int total = offset + data->data_len;
            if (total >= s.reasm_cap) {
                ESP_LOGW(TAG, "message too big (%d >= %d) - dropped",
                         total, s.reasm_cap);
                break;
            }
            s.reasm[total] = '\0';
            ws_msg_t m = { .kind = WS_MSG_TEXT, .len = total };
            xQueueSend(s.msg_queue, &m, portMAX_DELAY);
            /* Hand ownership of s.reasm to the worker until it has parsed
             * the message: the next fragment lands at offset 0 and would
             * otherwise overwrite the JSON mid-parse. */
            if (xSemaphoreTake(s.reasm_ack, pdMS_TO_TICKS(2000)) != pdTRUE) {
                ESP_LOGW(TAG, "worker did not release the reassembly buffer");
            }
        }
        break;
    }

    default:
        break;
    }
}

/* ------------------------------------------------------------- cleanup */

/* Free every resource ring_ws_init() may have allocated. Safe to call on a
 * zero-initialised context and on partial init failure. */
static void ws_release(void)
{
    if (s.msg_queue) { vQueueDelete(s.msg_queue); s.msg_queue = NULL; }
    if (s.event_queue) { vQueueDelete(s.event_queue); s.event_queue = NULL; }
    if (s.state_mutex) { vSemaphoreDelete(s.state_mutex); s.state_mutex = NULL; }
    if (s.reasm_ack) { vSemaphoreDelete(s.reasm_ack); s.reasm_ack = NULL; }
    if (s.worker_task) { vTaskDelete(s.worker_task); s.worker_task = NULL; }
    if (s.event_task) { vTaskDelete(s.event_task); s.event_task = NULL; }
    free(s.reasm); s.reasm = NULL;
    free(s.b64_text); s.b64_text = NULL;
    free(s.pcm24_scratch); s.pcm24_scratch = NULL;
    ring_byte_ring_deinit(&s.dl_ring);
}

/* ------------------------------------------------------------- public API */

esp_err_t ring_ws_init(ring_ws_state_cb_t state_cb,
                       ring_ws_transcript_cb_t text_cb,
                       ring_ws_tool_cb_t tool_cb,
                       void *user)
{
    memset(&s, 0, sizeof(s));
    s.state = RING_WS_OFF;
    s.state_cb = state_cb;
    s.text_cb = text_cb;
    s.tool_cb = tool_cb;
    s.user = user;

    s.msg_queue = xQueueCreate(16, sizeof(ws_msg_t));
    s.event_queue = xQueueCreate(1, sizeof(ring_ws_state_t));
    s.state_mutex = xSemaphoreCreateMutex();
    s.reasm_ack = xSemaphoreCreateBinary();
    if (s.msg_queue == NULL || s.event_queue == NULL ||
        s.state_mutex == NULL || s.reasm_ack == NULL) {
        ws_release();
        return ESP_ERR_NO_MEM;
    }

    if (ring_byte_ring_init(&s.dl_ring, RING_WS_DL_BYTES, MALLOC_CAP_SPIRAM) != ESP_OK) {
        ESP_LOGW(TAG, "downlink ring alloc failed (%d bytes)", RING_WS_DL_BYTES);
        ws_release();
        return ESP_ERR_NO_MEM;
    }
    s.reasm = heap_caps_malloc(RING_WS_REASM_BYTES, MALLOC_CAP_SPIRAM);
    if (s.reasm == NULL) {
        ESP_LOGW(TAG, "reassembly alloc failed (%d bytes)", RING_WS_REASM_BYTES);
        ws_release();
        return ESP_ERR_NO_MEM;
    }
    s.reasm_cap = RING_WS_REASM_BYTES;

    s.b64_cap = RING_WS_B64_MAX;
    s.b64_text = heap_caps_malloc(s.b64_cap, MALLOC_CAP_SPIRAM);
    s.pcm24_cap = RING_WS_PCM24_MAX;
    s.pcm24_scratch = heap_caps_malloc(s.pcm24_cap, MALLOC_CAP_SPIRAM);
    if (s.b64_text == NULL || s.pcm24_scratch == NULL) {
        ESP_LOGW(TAG, "delta scratch alloc failed (%u + %u bytes)",
                 (unsigned)s.b64_cap, (unsigned)s.pcm24_cap);
        ws_release();
        return ESP_ERR_NO_MEM;
    }

    ring_resample_decim_init(&s.decim);
    ring_resample_interp_init(&s.interp);

    xTaskCreate(worker_task, "ring-ws-worker", WS_WORKER_STACK, NULL,
                WS_WORKER_PRIO, &s.worker_task);
    xTaskCreate(event_task, "ring-ws-event", WS_EVENT_STACK, NULL,
                WS_EVENT_PRIO, &s.event_task);

    ESP_LOGI(TAG, "initialised");
    return ESP_OK;
}

esp_err_t ring_ws_start(const char *model, const char *api_key,
                        const ring_ws_session_cfg_t *cfg)
{
    if (model == NULL || api_key == NULL || cfg == NULL) {
        return ESP_ERR_INVALID_ARG;
    }
    snprintf(s.model, sizeof(s.model), "%s", model);
    snprintf(s.api_key, sizeof(s.api_key), "%s", api_key);
    s.cfg = *cfg;

    /* Negotiated mode starts as the requested mode (or "ptt"). */
    if (cfg->turn_detection == NULL) {
        snprintf(s.turn_mode, sizeof(s.turn_mode), "ptt");
    } else {
        snprintf(s.turn_mode, sizeof(s.turn_mode), "%s", cfg->turn_detection);
    }

    /* Reset stats. */
    s.bytes_up = s.bytes_down = s.turns = 0;
    s.dropped_up = s.dropped_down = 0;
    s.ring_high_samples = 0;
    s.buffered_high_ms = 0;
    s.responding = false;
    s.speaking = false;
    s.last_playback_ms = 0;
    s.cushion_ms = RING_WS_CUSHION_MS;
    /* Reset the resampler history and the downlink ring: stale samples from
     * a previous session would otherwise leak into the first frame/turn. */
    ring_resample_decim_init(&s.decim);
    ring_resample_interp_init(&s.interp);
    ring_byte_ring_reset(&s.dl_ring);

    /* Tear down any previous client first (B-3). */
    if (s.client != NULL) {
        esp_websocket_client_stop(s.client);
        esp_websocket_client_destroy(s.client);
        s.client = NULL;
    }

    state_set(RING_WS_CONNECTING);

    /* 1. Wi-Fi (idempotent, like ring_net). */
    esp_err_t err = ring_wifi_start();
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "wifi start: %s", esp_err_to_name(err));
        state_set(RING_WS_ERROR);
        return err;
    }
    err = ring_wifi_wait_connected(20000);
    if (err != ESP_OK) {
        ESP_LOGW(TAG, "no IP: %s", esp_err_to_name(err));
        state_set(RING_WS_ERROR);
        return err;
    }

    /* 2. Clock (TLS needs it). */
    err = ring_time_sync(RING_WS_SNTP_TIMEOUT_MS);
    if (err != ESP_OK) {
        state_set(RING_WS_ERROR);
        return err;
    }

    /* 3. WebSocket connect. */
    char uri[256];
    snprintf(uri, sizeof(uri), "wss://%s/api-ws/v1/realtime?model=%s",
             RING_WS_HOST, s.model);

    char auth_hdr[192];
    snprintf(auth_hdr, sizeof(auth_hdr),
             "Authorization: Bearer %s\r\n", s.api_key);

    esp_websocket_client_config_t ws_cfg = {
        .uri = uri,
        .cert_pem = ring_ws_ca_pem(),
        .cert_len = ring_ws_ca_pem_len(),
        .headers = auth_hdr,
        .buffer_size = 4096,
        .disable_auto_reconnect = true,
        .task_stack = 8192,
        .task_prio = 5,
        .ping_interval_sec = 15,
        .network_timeout_ms = 10000,
    };
    s.client = esp_websocket_client_init(&ws_cfg);
    if (s.client == NULL) {
        ESP_LOGE(TAG, "ws init failed");
        state_set(RING_WS_ERROR);
        return ESP_FAIL;
    }
    esp_websocket_register_events(s.client, WEBSOCKET_EVENT_ANY,
                                  ws_event_handler, NULL);
    esp_err_t wserr = esp_websocket_client_start(s.client);
    if (wserr != ESP_OK) {
        ESP_LOGE(TAG, "ws start: %s", esp_err_to_name(wserr));
        esp_websocket_client_destroy(s.client);
        s.client = NULL;
        state_set(RING_WS_ERROR);
        return wserr;
    }

    /* 4. Wait for session.updated. */
    ESP_LOGI(TAG, "waiting for session...");
    uint32_t deadline = now_ms() + RING_WS_SESSION_TIMEOUT_MS;
    for (;;) {
        ring_ws_state_t st = ring_ws_state();
        if (st != RING_WS_CONNECTING && st != RING_WS_OFF) {
            break;
        }
        if (now_ms() >= deadline) {
            break;
        }
        vTaskDelay(pdMS_TO_TICKS(50));
    }
    ring_ws_state_t st = ring_ws_state();
    if (st != RING_WS_READY && st != RING_WS_LISTENING &&
        st != RING_WS_SPEAKING) {
        ESP_LOGW(TAG, "session not ready (%s)", ring_ws_state_name(st));
        /* Don't leave a live client behind: the caller retries start(), which
         * would otherwise tear it down only after the retry began. */
        esp_websocket_client_stop(s.client);
        esp_websocket_client_destroy(s.client);
        s.client = NULL;
        state_set(RING_WS_ERROR);
        return ESP_ERR_TIMEOUT;
    }
    ESP_LOGI(TAG, "session ready (model %s, mode %s)", s.model, s.turn_mode);
    return ESP_OK;
}

esp_err_t ring_ws_stop(void)
{
    if (s.client != NULL) {
        esp_websocket_client_stop(s.client);
        esp_websocket_client_destroy(s.client);
        s.client = NULL;
    }
    s.responding = false;
    s.speaking = false;
    ring_byte_ring_reset(&s.dl_ring);
    ring_resample_decim_init(&s.decim);
    ring_resample_interp_init(&s.interp);
    state_set(RING_WS_OFF);
    return ESP_OK;
}

ring_ws_state_t ring_ws_state(void)
{
    if (s.state_mutex != NULL) {
        xSemaphoreTake(s.state_mutex, portMAX_DELAY);
    }
    ring_ws_state_t st = s.state;
    if (s.state_mutex != NULL) {
        xSemaphoreGive(s.state_mutex);
    }
    return st;
}

