#!/usr/bin/env python3
"""
gen_ws_resampler.py — Generate polyphase FIR filter tables for ringkit.

Output: components/ringkit/src/ring_resample_coeffs.c (coefficients only).
The resampling functions live in ring_resample.c.

Decimator:  48k -> 16k (D=3), ~63 taps, 21 per phase.
Interpolator: 24k -> 48k (I=2), ~24 taps, 12 per phase.
"""
import math

def i0(x):
    if abs(x) < 1e-12:
        return 1.0
    s = 1.0
    t = 1.0
    for k in range(1, 100):
        t *= (x * 0.5) ** 2 / (k * k)
        s += t
        if abs(t) < 1e-15:
            break
    return s

def kaiser(N, beta):
    denom = i0(beta)
    return [i0(beta * math.sqrt(1.0 - ((2.0 * n / (N - 1)) - 1.0) ** 2)) / denom for n in range(N)]

def design(in_rate, out_rate, total_taps, fc, beta):
    if in_rate > out_rate:
        D = in_rate // out_rate
        assert in_rate == out_rate * D
        P = D
    else:
        P = out_rate // in_rate
        assert out_rate == in_rate * P

    plen = total_taps // P
    N = plen * P
    # The prototype runs at the HIGHER of the two rates (input for a
    # decimator, output for an interpolator), so its normalised cutoff is
    # fc / max(fs_in, fs_out) cycles/sample.  Using min() here makes the
    # decimator an all-pass (no anti-alias filtering at all: everything
    # above 8 kHz folds into the 16 kHz speech band) and squeezes the
    # interpolator down to ~2.5 kHz (a muffled reply).
    wn = fc / max(in_rate, out_rate)
    assert wn < 0.5, "cutoff above Nyquist of the prototype rate"

    w = kaiser(N, beta)
    centre = (N - 1) * 0.5

    # prototype lowpass
    h = []
    for n in range(N):
        t = n - centre
        h.append(2.0 * wn * (math.sin(2 * math.pi * wn * t) / (2 * math.pi * wn * t) if abs(t) > 1e-12 else 1.0))
    for n in range(N):
        h[n] *= w[n]

    # deinterleave
    phases = [[h[p + k * P] for k in range(plen)] for p in range(P)]

    # Interpolation: zero-stuffing halves the average energy, so the
    # prototype needs a DC gain of I (=P) for each phase to sum to 1 and the
    # output amplitude to match the input.  A decimator needs gain 1.
    if in_rate < out_rate:
        phases = [[c * P for c in ph] for ph in phases]
    return P, plen, phases

def fmt(name, phases, w=14):
    # Non-static: ring_resample.c declares the tables extern.
    lines = [f"/* {name}: {len(phases)} phases x {len(phases[0])} taps */"]
    lines.append(f"const float {name}[{len(phases)}][{len(phases[0])}] = {{")
    for pi, phase in enumerate(phases):
        vals = ", ".join(f"{c:{w}.8f}f" for c in phase)
        lines.append(f"    {{ {vals} }}" + ("," if pi < len(phases) - 1 else ""))
    lines.append("};")
    return "\n".join(lines)

dp, dlen, dc = design(48000, 16000, 63, 7500.0, 5.0)
ip, ilen, ic = design(24000, 48000, 24, 11000.0, 4.5)

print(dp, dlen, len(dc[0]))
print(ip, ilen, len(ic[0]))

with open("components/ringkit/src/ring_resample_coeffs.c", "w") as f:
    f.write("/* Generated by tools/gen_ws_resampler.py. Do not edit. */\n")
    f.write("#include <stdint.h>\n\n")
    f.write("/* Decimator 48k->16k, D=%d, %d taps/phase */\n" % (dp, dlen))
    f.write(fmt("ring_resample_decim_coeffs", dc))
    f.write("\n\n")
    f.write("/* Interpolator 24k->48k, I=%d, %d taps/phase */\n" % (ip, ilen))
    f.write(fmt("ring_resample_interp_coeffs", ic))
    f.write("\n")

print("OK - generated coefficients")