#!/usr/bin/env python3
"""Pack a raw RGB888 blob (+ optional A8 matte) into an LVGL 9 image C file.

No Python imaging dependencies: the caller does the decoding/scaling with
ImageMagick and hands over raw planes. See notes/gbuddy.md §4.

  magick in.png -resize 360x222! -depth 8 rgb:/tmp/x.rgb
  magick in.png -alpha extract -depth 8 gray:/tmp/x.a8
  tools/lvgl_img_pack.py /tmp/x.rgb 360 222 out.c sym [/tmp/x.a8]

RGB565 is stored little-endian (native on the ESP32-S3); the display adapter
swaps bytes at flush time, so assets must NOT be pre-swapped.
"""
import os
import struct
import sys


def pack(src, w, h, out, name, alpha=None):
    w, h = int(w), int(h)
    rgb = open(src, "rb").read()
    if len(rgb) != w * h * 3:
        raise SystemExit(f"{src}: expected {w * h * 3} bytes of RGB888, got {len(rgb)}")

    a8 = None
    if alpha:
        a8 = open(alpha, "rb").read()
        if len(a8) != w * h:
            raise SystemExit(f"{alpha}: expected {w * h} bytes of A8, got {len(a8)}")

    cf = "LV_COLOR_FORMAT_RGB565A8" if a8 else "LV_COLOR_FORMAT_RGB565"
    px = bytearray()
    for i in range(0, len(rgb), 3):
        r, g, b = rgb[i], rgb[i + 1], rgb[i + 2]
        px += struct.pack("<H", ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    if a8:
        px += a8  # the A8 plane follows the colour plane (lv_draw_buf.c)

    with open(out, "w") as f:
        f.write(f"/* {w}x{h} {cf}, {len(px)} B — generated by tools/lvgl_img_pack.py\n"
                f" * from {os.path.basename(src)}" +
                (f" + {os.path.basename(alpha)}" if alpha else "") + ".\n"
                " * Do not edit by hand; re-run examples/gbuddy/assets/rebuild.sh. */\n")
        f.write('#include "lvgl.h"\n\n')
        f.write(f"static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {name}_map[] = {{\n")
        for i in range(0, len(px), 16):
            f.write("    " + ",".join(f"0x{b:02x}" for b in px[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write(f"const lv_image_dsc_t {name} = {{\n"
                f"    .header.magic = LV_IMAGE_HEADER_MAGIC,\n"
                f"    .header.cf = {cf},\n"
                f"    .header.w = {w},\n"
                f"    .header.h = {h},\n"
                f"    .header.stride = {w * 2},\n"
                f"    .data_size = sizeof({name}_map),\n"
                f"    .data = {name}_map,\n}};\n")
    print(f"{out}: {w}x{h} {cf} {len(px)} B")


if __name__ == "__main__":
    if len(sys.argv) < 6:
        raise SystemExit(__doc__)
    pack(*sys.argv[1:6], alpha=(sys.argv[6] if len(sys.argv) > 6 else None))
